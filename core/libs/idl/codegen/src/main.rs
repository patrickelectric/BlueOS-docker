//! Writes `src/generated.rs` and `api.lock` of blueos-idl from `interfaces/`. Run it after changing an interface:
//! `cargo run -p blueos-idl-codegen`. CI runs it too and fails when the committed files differ.

use std::{fmt::Write as _, path::Path, process::Command};

use roslibrust_codegen::{ArrayType, CodegenOptions, FieldInfo, FieldType};

const ACTION_PARTS: [&str; 3] = ["Goal", "Result", "Feedback"];
// roslibrust also expands an action the ROS 1 way, with wrappers that need actionlib_msgs; ROS 2 does not use them.
const ROS1_ACTION_WRAPPERS: [&str; 4] = ["Action", "ActionGoal", "ActionResult", "ActionFeedback"];

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let idl = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let (messages, mut services, actions) = roslibrust_codegen::find_and_parse_ros_messages(&[idl.join("interfaces")])?;

    let mut messages: Vec<_> = messages
        .into_iter()
        .filter(|message| {
            let is_wrapper = ROS1_ACTION_WRAPPERS.iter().any(|suffix| {
                actions
                    .iter()
                    .any(|action| message.name == format!("{}{suffix}", action.name))
            });
            !is_wrapper
        })
        .collect();

    let mut schema_names = Vec::new();
    let mut lock = String::new();
    for message in &mut messages {
        let package = message.package.clone();
        pad_empty(&mut message.fields, &package);
        let schema_name = actions
            .iter()
            .filter(|action| action.package == package)
            .find_map(|action| {
                let part = message.name.strip_prefix(action.name.as_str())?;
                ACTION_PARTS
                    .contains(&part)
                    .then(|| format!("{package}/action/{}_{part}", action.name))
            })
            .unwrap_or_else(|| format!("{package}/msg/{}", message.name));
        writeln!(lock, "{schema_name}: {}", signature(&message.fields))?;
        schema_names.push((format!("{package}::{}", message.name), schema_name));
    }
    for service in &mut services {
        let package = service.package.clone();
        for (part, message) in [
            ("Request", &mut service.request_type),
            ("Response", &mut service.response_type),
        ] {
            pad_empty(&mut message.fields, &package);
            let schema_name = format!("{package}/srv/{}_{part}", service.name);
            writeln!(lock, "{schema_name}: {}", signature(&message.fields))?;
            schema_names.push((format!("{package}::{}{part}", service.name), schema_name));
        }
    }

    let (messages, services) = roslibrust_codegen::resolve_dependency_graph(messages, services)?;
    let options = CodegenOptions {
        generate_definition: true,
        roslibrust_serde: false,
    };
    // The files are found in directory order, which changes from one run to the next.
    schema_names.sort_unstable();
    let mut generated =
        String::from("// Generated by blueos-idl-codegen from core/libs/idl/interfaces, do not edit.\n");
    generated.push_str(
        &roslibrust_codegen::generate_rust_ros_message_definitions(messages, services, &options)?.to_string(),
    );
    for (path, schema_name) in schema_names {
        write!(
            generated,
            "impl crate::Message for {path} {{ const SCHEMA_NAME: &'static str = \"{schema_name}\"; }}"
        )?;
    }

    let generated_path = idl.join("src/generated.rs");
    std::fs::write(&generated_path, generated)?;
    let formatted = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(&generated_path)
        .status()?;
    if !formatted.success() {
        return Err("rustfmt failed on the generated code".into());
    }
    let mut lock_lines: Vec<_> = lock.lines().collect();
    lock_lines.sort_unstable();
    std::fs::write(idl.join("api.lock"), lock_lines.join("\n") + "\n")?;
    Ok(())
}

/// Gives an empty message the one byte ROS 2 writes for it, so no message is zero-sized on the wire.
fn pad_empty(fields: &mut Vec<FieldInfo>, package: &str) {
    if fields.is_empty() {
        fields.push(FieldInfo {
            field_type: FieldType {
                package_name: None,
                source_package: package.to_owned(),
                field_type: "uint8".to_owned(),
                array_info: ArrayType::NotArray,
                string_capacity: None,
            },
            field_name: "structure_needs_at_least_one_member".to_owned(),
            default: None,
        });
    }
}

/// The fields as `api.lock` records them: `type name` in wire order.
fn signature(fields: &[FieldInfo]) -> String {
    fields
        .iter()
        .map(|field| match &field.field_type.package_name {
            Some(package) => format!("{package}/{} {}", field.field_type, field.field_name),
            None => format!("{} {}", field.field_type, field.field_name),
        })
        .collect::<Vec<_>>()
        .join(", ")
}
